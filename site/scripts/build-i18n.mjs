/**
 * Merge site/lang/{en,fr}/*.json (fixed order), apply manifest version tokens to all string values,
 * and write site/src/vendor/hub-energie-i18n.js for Vue (see src/main.js).
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  applyHubEnergieVersionTokens,
  hubEnergieVersionSeries,
  readHubEnergieManifestVersion,
} from "./manifest-version.mjs";

const __root = dirname(fileURLToPath(import.meta.url));
const siteDir = join(__root, "..");
const vendorDir = join(siteDir, "src", "vendor");

/** Same order as extract-lang-from-legacy-i18n.mjs scopes */
const MERGE_ORDER = ["common", "landing", "doc", "developers", "flowsim", "flowhelp", "internals"];

function mergeLocale(lang) {
  const out = {};
  for (const name of MERGE_ORDER) {
    const p = join(siteDir, "lang", lang, `${name}.json`);
    if (!existsSync(p)) {
      console.error(`hub_energie site: missing ${p}`);
      process.exit(1);
    }
    const o = JSON.parse(readFileSync(p, "utf8"));
    for (const k of Object.keys(o)) {
      if (Object.prototype.hasOwnProperty.call(out, k)) {
        console.error(`hub_energie site: duplicate i18n key "${k}" in ${name}.json (${lang})`);
        process.exit(1);
      }
      out[k] = o[k];
    }
  }
  return out;
}

function mapDeepStrings(value, fn) {
  if (typeof value === "string") return fn(value);
  if (value !== null && typeof value === "object" && !Array.isArray(value)) {
    const next = {};
    for (const [k, v] of Object.entries(value)) {
      next[k] = mapDeepStrings(v, fn);
    }
    return next;
  }
  return value;
}

function fixDocHashHref(s) {
  return s.replace(/href=\\"#doc\\"/g, 'href=\\"#/doc\\"').replace(/href="#doc"/g, 'href="#/doc"');
}

function postProcessStrings(s) {
  return fixDocHashHref(applyHubEnergieVersionTokens(s));
}

mkdirSync(vendorDir, { recursive: true });

const en = mapDeepStrings(mergeLocale("en"), postProcessStrings);
const fr = mapDeepStrings(mergeLocale("fr"), postProcessStrings);

const manifestFull = readHubEnergieManifestVersion();
const manifestSeries = hubEnergieVersionSeries(manifestFull);

const payload = JSON.stringify({ en, fr }, null, 2);
const banner = `/**
 * Hub Énergie documentation — static i18n (en / fr). Generated by scripts/build-i18n.mjs.
 * Source: site/lang/{en,fr}/*.json. Keys via data-i18n (plain text; structure lives in Vue).
 * Version tokens expanded from custom_components/hub_energie/manifest.json at build time.
 * HubEnergieManifestVersion / HubEnergieManifestVersionSeries: same source, for Vue badges.
 */
`;

const body = `${banner}(function (global) {
  "use strict";
  global.HubEnergieI18n = ${payload};
  global.HubEnergieManifestVersion = ${JSON.stringify(manifestFull)};
  global.HubEnergieManifestVersionSeries = ${JSON.stringify(manifestSeries)};
})(typeof window !== "undefined" ? window : globalThis);
`;

writeFileSync(join(vendorDir, "hub-energie-i18n.js"), body, "utf8");
console.log("hub_energie site: wrote", join("src", "vendor", "hub-energie-i18n.js"));
